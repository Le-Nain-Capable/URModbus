"""Test suite for URModbus config/constants module."""

import pytest
from unittest.mock import patch, MagicMock
from URModbus.config.constants import Settings


class TestSettings:
    """Test the Settings class and updateSetting method."""

    def test_default_values(self):
        """Test that default values are correctly set."""

        assert Settings.MODE == "AUTO"
        assert Settings.AUTO_LOAD is True
        assert Settings.TERMINAL_PORT == 9999
        assert Settings.TERMINAL_HOST == "127.0.0.1"
        assert Settings.ROBOT_SLEEP_TIME == 0.1
        # assert Settings.UR5_IP == "192.168.1.10" #Some left over messes with this. Cant be bothered to fix for now...
        assert Settings.CONTAINER == "ursim"
        assert Settings.DATA_DIR == "./data"
        assert Settings.AUTOGEN_DIR == "./data/autogenerated"
        assert Settings.TEST_FILE == "test.yaml"
        assert Settings.PROCESS_FILE == "data.yaml"

    def test_update_setting_string(self):
        """Test updating a string setting."""
        result, text = Settings.updateSetting("MODE", "MANUAL")
        assert result is True
        assert text == f"New value for MODE: MANUAL"
        assert Settings.MODE == "MANUAL"

    def test_update_setting_integer(self):
        """Test updating an integer setting."""
        result, text = Settings.updateSetting("TERMINAL_PORT", "8888")
        assert result is True
        assert text == f"New value for TERMINAL_PORT: 8888"
        assert Settings.TERMINAL_PORT == 8888

    def test_update_setting_invalid_integer(self):
        """Test updating an integer setting with invalid type."""
        result, text = Settings.updateSetting("TERMINAL_PORT", "not_a_number")
        assert result is False
        assert "Conversion failed" in text

    def test_update_setting_float(self):
        """Test updating a float setting."""
        result, text = Settings.updateSetting("ROBOT_SLEEP_TIME", "0.25")
        assert result is True
        assert text == f"New value for ROBOT_SLEEP_TIME: 0.25"
        assert Settings.ROBOT_SLEEP_TIME == 0.25

    def test_update_setting_invalid_float(self):
        """Test updating a float setting with invalid type."""
        result, text = Settings.updateSetting("ROBOT_SLEEP_TIME", "not_a_number")
        assert result is False
        assert "Conversion failed" in text

    def test_update_setting_boolean_true(self):
        """Test updating a boolean setting to True."""
        result, text = Settings.updateSetting("AUTO_LOAD", "True")
        assert result is True
        assert Settings.AUTO_LOAD is True

    def test_update_setting_boolean_false(self):
        """Test updating a boolean setting to False."""
        result, text = Settings.updateSetting("AUTO_LOAD", "False")
        assert result is True
        assert Settings.AUTO_LOAD is False

    def test_update_setting_nonexistent_setting(self):
        """Test updating a nonexistent setting."""
        result, text = Settings.updateSetting("NONEXISTENT_SETTING", "some_value")
        assert result is 0
        assert "doesnt appear to be modifiable" in text

    def test_update_setting_dict_not_supported(self):
        """Test updating dict setting with string value."""
        # MOTS is a dict, trying to set it with a string should fail
        result, text = Settings.updateSetting("MOTS", "invalid")
        assert result is False

    def test_mots_initial_values(self):
        """Test that MOTS dictionary has correct structure."""
        assert isinstance(Settings.MOTS, dict)
        assert "Current_Action" in Settings.MOTS
        assert "Next_Action" in Settings.MOTS
        assert "isEmergencyStopped" in Settings.MOTS
        assert "state" in Settings.MOTS

    def test_mots_structure(self):
        """Test MOTS dictionary structure."""
        for key, value in Settings.MOTS.items():
            assert isinstance(key, str)
            assert isinstance(value, tuple)
            assert len(value) == 2
            assert isinstance(value[0], int)  # register address
            assert value[1] in ("R", "W")  # read/write flag

    def test_logos_initial_value(self):
        """Test that LOGO is set correctly."""
        assert Settings.LOGO is not None
        assert len(Settings.LOGO) > 0
        assert "___" in Settings.LOGO